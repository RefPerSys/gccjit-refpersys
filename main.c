double
wallclock_real_time_HDGJIRPS (void)
{
  struct timespec ts = { 0, 0 };
  if (clock_gettime (CLOCK_REALTIME, &ts))
    return NAN;
  return 1.0 * ts.tv_sec + 1.0e-9 * ts.tv_nsec;
}				/* end wallclock_real_time_HDGJIRPS */

