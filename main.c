void
parse_program_option_HDGJIRPS (int argc, char **argv)
{
  //     extern char *optarg;
  //     extern int optind, opterr, optopt;
  int opt = -1;
  int ix = -1;
  do
    {
      opt = getopt_long (argc, argv, "VvHl:", progopt_HDGJIRPS, &ix);
      switch (opt)
	{
	case 0:
	  continue;
	case -1:
	  break;
	case 'V':		/* --verbose */
	  printf ("%s is verbose (pid %d on %s), GPLv3+ licensed\n",
		  progname_HDGJIRPS, (int) getpid (), hostname_HDGJIRPS);
	  verbose_HDGJIRPS = 1;
	  break;
	case 'v':		/* --version */
	  printf ("%s version gitid %s built on %s\n", progname_HDGJIRPS,
		  shortgitid_HDGJIRPS, __DATE__ "@" __TIME__);
	  printf ("\t C version %ld, compiler %s\n", __STDC_VERSION__,
		  __VERSION__);
	  printf ("\t libunistring version: %d.%d.%d\n",
		  _libunistring_version >> 16,
		  0xff & (_libunistring_version >> 8),
		  _libunistring_version & 0xff);
	  printf ("\t GNU libc version: %s [%s]\n", gnu_get_libc_version (),
		  gnu_get_libc_release ());
	  printf ("\t libgccjit version: %d.%d.%d\n",
		  gcc_jit_version_major (), gcc_jit_version_minor (),
		  gcc_jit_version_patchlevel ());
	  printf ("%s is GPLv3+ licensed, so WITHOUT WARRANTY;\n"
		  " see www.gnu.org/licenses/gpl-3.0.html\n",
		  progname_HDGJIRPS);
	  printf ("\t Its source code could be on %s\n",
		  "github.com/RefPerSys/gccjit-refpersys/");
	  break;
	case 'H':		/* --help */
	  program_usage_HDGJIRPS ();
	  break;
	case 'l':
	  if (loadpath_HDGJIRPS)
	    HDGJIRPS_FATAL ("cannot load more than once (%s & %s)",
			    loadpath_HDGJIRPS, optarg);
	  loadpath_HDGJIRPS = optarg;
	  break;
	case random_optHDGJIRPS:
	  printf ("%ld\n", (long) randomi64_HDGJIRPS ());
	  break;
	default:
	  break;
	};
    }
  while (opt >= 0);
}				/* end parse_program_option_HDGJIRPS */


void
load_file_HDGJIRPS (const char *ldpath)
{
  extern void load_state_HDGJIRPS (const char *path, const void *start,
				   const void *last);
  struct stat ldstat = { };
  int ldfd = open (ldpath, R_OK);
  if (ldfd < 0)
    HDGJIRPS_FATAL ("%s failed to open loaded file %s (%s)",	//
		    progname_HDGJIRPS, ldpath, strerror (errno));
  if (!jitctx_HDGJIRPS)
    HDGJIRPS_FATAL ("%s without jitctx_HDGJIRPS", progname_HDGJIRPS);
  if (fstat (ldfd, &ldstat))
    HDGJIRPS_FATAL ("%s failed to fstat loaded file %s (%s) fd#%d",	//
		    progname_HDGJIRPS, ldpath, strerror (errno), ldfd);
  size_t ldsize = ldstat.st_size;
  size_t pgsize = getpagesize ();
  size_t memsize = (ldsize % pgsize) ? (1 + (ldsize | (pgsize - 1))) : ldsize;
  size_t mmapsize = memsize;
  if (verbose_HDGJIRPS)
    {
      printf ("%s: [%s:%d] mmap mmapsize=%zd ldfd#%d ldsize=%zd ldpath:%s\n",
	      progname_HDGJIRPS, __FILE__, __LINE__ - 1, mmapsize, ldfd,
	      ldsize, ldpath);
      fflush (NULL);
    }
  const void *ldad = mmap (NULL, mmapsize, PROT_READ,
			   MAP_SHARED,	/* MAP_HUGETLB dont work here */
			   ldfd, 0);
  if (ldad == MAP_FAILED)
    HDGJIRPS_FATAL ("%s failed to mmap fd#%d (%zd Kbytes)"
		    " for loaded file %s (%s)",
		    progname_HDGJIRPS, ldfd, mmapsize >> 10, ldpath,
		    strerror (errno));
  const void *ldend = (const char *) ldad + mmapsize;
  if (ldsize % pgsize == 0)
    {
      const void *zad = mmap ((void *) ldend, pgsize, PROT_READ,
			      MAP_FIXED | MAP_PRIVATE | MAP_ANON,	/* MAP_HUGETLB dont work here */
			      -1, 0);
      if (zad != ldend)
	HDGJIRPS_FATAL ("%s failed to mmap zero page at %p"
			" for loaded file %s (%s)",
			progname_HDGJIRPS, ldend, ldpath, strerror (errno));
    };
  assert (*(const char *) ldend == (char) 0);
  if (verbose_HDGJIRPS)
    {
      printf ("%s mmaped loaded file %s (fd#%d) for %zd Kbytes @%p-%p\n",
	      progname_HDGJIRPS, ldpath, ldfd, mmapsize >> 10, ldad, ldend);
      fflush (NULL);
    };
  load_state_HDGJIRPS (ldpath, ldad, ldend);
}				/* end load_file_HDGJIRPS */

static void
getexec_HDGJIRPS (void)
{
  ssize_t s = readlink ("/proc/self/exe",
			executable_HDGJIRPS,
			sizeof (executable_HDGJIRPS) - 1);
  if (s < 0 || !executable_HDGJIRPS[0])
    HDGJIRPS_FATAL ("%s failed to readlink /proc/self/exe (%s)",
		    progname_HDGJIRPS, strerror (errno));
  if (access (executable_HDGJIRPS, R_OK | X_OK))
    HDGJIRPS_FATAL ("%s has bad executable %s (%s)",
		    progname_HDGJIRPS, executable_HDGJIRPS, strerror (errno));
}				/* end getexec_HDGJIRPS */

